def glyph(rows, accent=None):
    pen = TTGlyphPen(None)
    pixels = [(column, 6-row) for row, line in enumerate(rows) for column, bit in enumerate(line) if bit == '1']
    if accent == 'acute': pixels += [(2,8),(3,9)]
    if accent == 'tilde': pixels += [(0,8),(1,9),(2,9),(3,8),(4,9)]
    if accent == 'umlaut': pixels += [(1,8),(3,8)]
    for x,y in pixels:
        x,y = x*100,y*100
        pen.moveTo((x,y));pen.lineTo((x,y+100));pen.lineTo((x+100,y+100));pen.lineTo((x+100,y));pen.closePath()
    return pen.glyph()

fb = FontBuilder(1000, isTTF=True)
characters = ''.join(PATTERNS) + 'abcdefghijklmnopqrstuvwxyzÁÉÍÓÚÑÜáéíóúñü'
cmap = {ord(char):f'uni{ord(char):04X}' for char in characters}
glyphs = {'.notdef':glyph(PATTERNS['?'])}
for char in characters:
    upper = char.upper()
    base = unicodedata.normalize('NFD',upper)[0]
    accent = 'tilde' if upper=='Ñ' else 'umlaut' if upper=='Ü' else 'acute' if upper in 'ÁÉÍÓÚ' else None
    glyphs[cmap[ord(char)]] = glyph(PATTERNS[base],accent)
fb.setupGlyphOrder(list(glyphs))
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({name:(600,0) for name in glyphs})
fb.setupHorizontalHeader(ascent=1000,descent=-200)
fb.setupNameTable({'familyName':'Lab Pixel','styleName':'Regular','uniqueFontIdentifier':'MendezLabPixel1','fullName':'Lab Pixel Regular','psName':'LabPixel-Regular','version':'Version 1.0'})
fb.setupOS2(sTypoAscender=1000,sTypoDescender=-200,usWinAscent=1000,usWinDescent=200)
fb.setupPost()
fb.setupMaxp()
fb.font['head'].created = fb.font['head'].modified = 3800000000
fb.font.recalcTimestamp = False
fb.font.flavor='woff2'
output = Path(__file__).resolve().parents[1] / 'dist/assets/lab-pixel.woff2'
fb.save(output)
